import assert from 'node:assert/strict';
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { resolve, dirname } from 'node:path';
import { typescriptStructure } from './typescript-structure.mjs';

// Generate explicit, reviewable functions from the separately verified Part 01 inventory.
// Unsupported source types fail generation; no C# stream/internal command is exposed to browsers.
const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const matrix = JSON.parse(readFileSync(resolve(root, 'docs/contracts/api-ui-matrix.json'), 'utf8'));
const inventory = JSON.parse(readFileSync(resolve(root, 'docs/contracts/backend-schemas.json'), 'utf8'));
const schemas = new Map(inventory.schemas.map((schema) => [schema.name, schema]));
const enums = new Set(inventory.enums.map((item) => item.name));
const queryNames = new Set(matrix.operations.map((operation) => operation.query).filter(Boolean));
const selected = new Set();
const primitive = { string: 'string', Guid: 'Guid', DateTimeOffset: 'OffsetDateTime', int: 'number', long: 'number', decimal: 'number', bool: 'boolean', IFormFile: 'File' };

function typeOf(value) {
  if (value.endsWith('?')) return `${typeOf(value.slice(0, -1))} | null`;
  const list = value.match(/^(?:IReadOnly(?:List|Collection)|IEnumerable)<(.+)>$/);
  if (list) return `ReadonlyArray<${typeOf(list[1])}>`;
  if (value.startsWith('PaginationResult<')) return `PaginationResult<${typeOf(value.slice(17, -1))}>`;
  if (primitive[value]) return primitive[value];
  if (enums.has(value)) return value;
  assert(schemas.has(value), `Unsupported wire type: ${value}`);
  selected.add(value);
  return value;
}
for (const operation of matrix.operations) {
  if (operation.body) typeOf(operation.body);
  if (operation.query) typeOf(operation.query);
  typeOf(operation.response.slice('ApiResponse<'.length, -1));
}
typeOf('CsrfTokenResponse');
// Set iteration visits nested shapes added during traversal.
for (const name of selected) for (const property of schemas.get(name).properties) typeOf(property.csharpType);

const banner = '// Generated by scripts/generate-services.mjs from verified backend contracts. Do not hand-edit.\n';
function output(path, content) {
  const target = resolve(root, path);
  if (process.argv.includes('--check')) {
    assert.equal(typescriptStructure(readFileSync(target, 'utf8')), typescriptStructure(content), `Stale ${path}`);
  } else {
    mkdirSync(dirname(target), { recursive: true });
    writeFileSync(target, content, 'utf8');
  }
}
let types = `${banner}\n/** Wire identifiers and offset timestamps remain strings; display formatting is separate. */\nexport type Guid = string;\nexport type OffsetDateTime = string;\n\nexport interface ApiResponse<T> { success: true; data: T; message: string | null }\nexport interface PaginationResult<T> { items: ReadonlyArray<T>; pageNumber: number; pageSize: number; totalCount: number; totalPages: number }\n`;
for (const item of inventory.enums) {
  types += `\nexport const ${item.name} = {\n${item.members.map((member) => `  ${member.name}: ${member.value},`).join('\n')}\n} as const;\nexport type ${item.name} = (typeof ${item.name})[keyof typeof ${item.name}];\n`;
}
types += '\nexport interface ApiErrorResponse { success: false; code: FeatureErrorCode; message: string; errors: Readonly<Record<string, ReadonlyArray<string>>> | null }\n';
for (const name of [...selected].sort()) {
  const schema = schemas.get(name);
  types += `\n/** ${schema.source} */\nexport interface ${name} {\n`;
  for (const property of schema.properties) {
    // Query defaults/unused nullable filters may be omitted. Body shapes stay full, including nulls.
    const optional = queryNames.has(name) && !property.requiredMember && (property.nullable || property.defaultExpression !== null);
    types += `  ${property.name}${optional ? '?' : ''}: ${typeOf(property.csharpType)};\n`;
  }
  types += '}\n';
}
output('src/Types/contracts.ts', types);

const groups = Map.groupBy(matrix.operations, (operation) => operation.service.split('/')[1]);
let paths = `${banner}\nimport { ApiError } from '../Types/failures';\n\nexport { routePaths } from './browserPaths';\n\nfunction segment(value: string): string {\n  if (typeof value !== 'string' || !value || value === '.' || value === '..') throw new ApiError('unknown');\n  try { return encodeURIComponent(value); } catch { throw new ApiError('unknown'); }\n}\n\nexport const apiPaths = {\n  Security: { csrf: '/api/v1/auth/csrf' },\n`;
const lower = (value) => value[0].toLowerCase() + value.slice(1);
for (const [group, operations] of groups) {
  paths += `  ${group}: {\n`;
  for (const operation of operations) {
    const parameters = [...operation.route.matchAll(/\{(\w+)\}/g)].map((match) => match[1]);
    const path = operation.route.replace(/\{(\w+)\}/g, (_, name) => `\${segment(${name})}`);
    paths += `    ${lower(operation.action)}: ${parameters.length ? `(${parameters.map((name) => `${name}: string`).join(', ')}) => \`${path}\`` : `'${path}'`},\n`;
  }
  paths += '  },\n';
}
paths += '} as const;\n';
output('src/Router/routePaths.ts', paths);

for (const [group, operations] of groups) {
  const imports = new Set();
  const functions = [];
  for (const operation of operations) {
    const parameters = [...operation.route.matchAll(/\{(\w+)\}/g)].map((match) => match[1]);
    const result = typeOf(operation.response.slice('ApiResponse<'.length, -1));
    for (const name of result.match(/[A-Z]\w+/g) ?? []) if (name !== 'ReadonlyArray') imports.add(name);
    const properties = parameters.map((name) => `${name}: Guid`);
    if (parameters.length) imports.add('Guid');
    if (operation.query) {
      imports.add(operation.query);
      const required = schemas.get(operation.query).properties.some((property) => property.requiredMember || (!property.nullable && property.defaultExpression === null));
      properties.push(`query${required ? '' : '?'}: ${operation.query}`);
    }
    if (operation.body) { imports.add(operation.body); properties.push(`body: ${operation.body}`); }
    const optionalArgs = !parameters.length && !operation.body && (!operation.query || properties.every((property) => property.startsWith('query?')));
    const args = properties.length ? `args: { ${properties.join('; ')} }${optionalArgs ? ' = {}' : ''}, ` : '';
    let body = operation.body ? 'args.body' : undefined;
    let setup = '';
    if (operation.contentType === 'multipart/form-data') {
      const upload = schemas.get(operation.body).properties;
      assert.deepEqual(upload.filter((property) => property.csharpType === 'IFormFile').map((property) => property.name), ['file']);
      const metadata = upload.filter((property) => property.name !== 'file');
      assert(metadata.every((property) => ['altText', 'description'].includes(property.name)));
      setup = `  const form = new FormData();\n  form.append('File', args.body.file);\n${metadata.map((property) => `  if (args.body.${property.name} !== null) form.append('${property.name[0].toUpperCase() + property.name.slice(1)}', args.body.${property.name});\n`).join('')}`;
      body = 'form';
    }
    const method = lower(operation.action);
    const path = `apiPaths.${group}.${method}${parameters.length ? `(${parameters.map((name) => `args.${name}`).join(', ')})` : ''}`;
    const identityChange = ['RegisterCustomer', 'LoginCustomer', 'LoginUser', 'RefreshCustomerSession', 'RefreshUserSession', 'LogoutCustomer', 'LogoutUser', 'ChangeCustomerPassword', 'ChangeUserPassword'].includes(operation.action);
    const excluded = operation.route.startsWith('/api/v1/auth/') || ['GetCurrentCustomer', 'GetCurrentUser'].includes(operation.action);
    const metadata = `{ operation: '${operation.action}', authenticated: ${operation.policy !== 'Anonymous'}, skipAuthenticationRecovery: ${excluded ? 'true' : 'options.skipAuthenticationRecovery === true'}, changesIdentity: ${identityChange}, sessionControl: options.sessionControl === true }`;
    functions.push(`/** ${operation.method} ${operation.route} — ${operation.policy}; returns unwrapped domain data. */\nexport async function ${method}(${args}options: RequestOptions = {}): Promise<${result}> {\n${setup}  return apiRequest<${result}>({ method: '${operation.method}', path: ${path},${operation.query ? '\n    query: approvedQuery(args.query, ' + JSON.stringify(schemas.get(operation.query).properties.map((property) => property.name)) + '),' : ''}${body ? `\n    body: ${body},` : ''}\n    metadata: ${metadata}, ...(options.signal ? { signal: options.signal } : {}) });\n}\n`);
  }
  output(`src/Services/${group}.ts`, `${banner}\nimport { apiRequest } from '../API';\nimport { apiPaths } from '../Router/routePaths';\nimport type { RequestOptions } from '../Types/transport';\n${operations.some((operation) => operation.query) ? "import { approvedQuery } from './query';\n" : ''}import type { ${[...imports].sort().join(', ')} } from '../Types/contracts';\n\n${functions.join('\n')}`);
}
console.log(`${process.argv.includes('--check') ? 'Verified' : 'Generated'} ${matrix.operations.length} typed operations, ${selected.size} wire shapes and ${inventory.enums.length} numeric enums.`);
